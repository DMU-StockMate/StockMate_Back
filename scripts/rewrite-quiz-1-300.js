const mc = (question_text, correct, wrong, explanation) => ({
  question_type: 'MULTIPLE_CHOICE',
  question_text,
  explanation,
  choices: [correct, ...wrong.slice(0, 3)].map((text, i) => ({ no: i + 1, text, correct: i === 0 })),
});

const ox = (question_text, yes, explanation) => ({
  question_type: 'OX',
  question_text,
  explanation,
  choices: [{ no: 1, text: 'O', correct: yes }, { no: 2, text: 'X', correct: !yes }],
});

const rotate = (q, seed) => {
  if (q.question_type !== 'MULTIPLE_CHOICE') return q;
  const n = seed % 4;
  q.choices = q.choices.slice(n).concat(q.choices.slice(0, n)).map((c, i) => ({ ...c, no: i + 1 }));
  return q;
};


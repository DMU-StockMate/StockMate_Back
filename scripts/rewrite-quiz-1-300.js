function fallbackOx(code, n) {
  const [term, def, focus] = p[code];
  return n % 2 === 0
    ? ox(`${term}를 볼 때는 기준 기간과 조건을 함께 확인해야 한다.`, true, `맞다. ${term}는 ${def}이므로 조건에 따라 해석이 달라질 수 있다.`)
    : ox(`${term}는 항상 투자 결과를 확정해 주는 신호다.`, false, `틀리다. ${focus}`);
}

const groups = {};
for (const q of qs.slice(0, 300)) (groups[q.detail_code] ||= []).push(q);

for (const [code, rows] of Object.entries(groups)) {
  const mcs = buildMcPool(code);
  const oxs = buildOxPool(code);
  let mi = 0, oi = 0;
  for (const q of rows) {
    const next = q.question_type === 'OX'
      ? (oxs[oi++] || fallbackOx(code, oi))
      : (mcs[mi++] || fallbackMc(code, mi));
    Object.assign(q, rotate(JSON.parse(JSON.stringify(next)), q.num));
  }
}

const seen = new Set();
for (const q of qs.slice(0, 300)) {
  if (!seen.has(q.question_text)) {
    seen.add(q.question_text);
    continue;
  }
  const [term] = p[q.detail_code];
  q.question_text = `${term} 추가 사례 ${q.num}: 가장 적절한 설명은?`;
  seen.add(q.question_text);
}

